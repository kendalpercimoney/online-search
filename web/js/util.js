// Small shared helpers.

export const $ = (id) => document.getElementById(id);

export const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

export const plural = (n, word) => `${n} ${word}${n === 1 ? '' : 's'}`;

export function timecode(sec) {
  if (!isFinite(sec)) return '--:--';
  sec = Math.max(0, sec);
  const h = Math.floor(sec / 3600), m = Math.floor((sec % 3600) / 60), s = Math.floor(sec % 60);
  const mm = String(m).padStart(2, '0'), ss = String(s).padStart(2, '0');
  return h ? `${h}:${mm}:${ss}` : `${mm}:${ss}`;
}

export function bytes(n) {
  if (!n) return '';
  const u = ['B', 'KB', 'MB', 'GB', 'TB'];
  const i = Math.min(u.length - 1, Math.floor(Math.log(n) / Math.log(1024)));
  return `${(n / 1024 ** i).toFixed(i ? 1 : 0)} ${u[i]}`;
}

export function parseFolderId(input) {
  input = input.trim();
  if (!input) return '';
  return input.match(/folders\/([\w-]+)/)?.[1] || input.match(/[?&]id=([\w-]+)/)?.[1] || input;
}

export function debounce(fn, ms) {
  let timer;
  const debounced = (...args) => {
    clearTimeout(timer);
    timer = setTimeout(() => fn(...args), ms);
  };
  debounced.cancel = () => clearTimeout(timer);
  return debounced;
}

// Runs fn over items with at most `limit` in flight; results keep the input order.
export async function mapLimit(items, limit, fn) {
  const out = new Array(items.length);
  let next = 0;
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (next < items.length) {
      const i = next++;
      out[i] = await fn(items[i], i);
    }
  }));
  return out;
}

// A Map that forgets its least recently used entries beyond `max`, calling onEvict.
export class LRU extends Map {
  constructor(max, onEvict = () => {}) {
    super();
    this.max = max;
    this.onEvict = onEvict;
  }
  get(key) {
    if (!super.has(key)) return undefined;
    const value = super.get(key);
    super.delete(key);
    super.set(key, value);
    return value;
  }
  set(key, value) {
    super.delete(key);
    super.set(key, value);
    for (const [k, v] of this) {
      if (this.size <= this.max) break;
      super.delete(k);
      this.onEvict(v, k);
    }
    return this;
  }
}

// Builds an element: el('div', { className: 'x', onclick }, child, 'text', …).
export function el(tag, props = {}, ...children) {
  const node = document.createElement(tag);
  for (const [k, v] of Object.entries(props)) {
    if (v == null || v === false) continue;
    if (k === 'html') node.innerHTML = v;
    else if (k.startsWith('on')) node.addEventListener(k.slice(2), v);
    else if (k in node && typeof v !== 'string') node[k] = v;
    else if (k === 'className' || k === 'textContent' || k === 'title' || k === 'href' || k === 'hidden') node[k] = v;
    else node.setAttribute(k, v === true ? '' : v);
  }
  node.append(...children.flat().filter((c) => c != null && c !== false));
  return node;
}

